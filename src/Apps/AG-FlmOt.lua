-- Which files exist, checked once in init() (R6).
local audio = { ok = false, tlost = false, armed = false, relit = false }

-- Jeti's io is function-style (constitution III). The transmitter opens
-- "/Apps/..."; the JETI Studio emulator (6.04) only opens the same path
-- without the leading "/" (2026-10-05), so try that too. Only this check
-- uses it: playback keeps the absolute path.
local function fileExists(path)
  local f = io.open(path, "r") or io.open(string.sub(path, 2), "r")
  if f then
    io.close(f)
    return true
  end
  return false
end

local function checkAudio()
  audio.ok = fileExists(SND.cycle) and fileExists(SND.cycletl)
  audio.tlost = fileExists(SND.tlost)
  audio.armed = fileExists(SND.armed)
  audio.relit = fileExists(SND.relit)
end

-- Starts one alarm cycle (R2, R6, R7). AUDIO_IMMEDIATE stops any other
-- foreground playback, so the alarm pre-empts other apps' speech (FR-025).
-- Without the cycle files: two bursts of beeps, the second 2.5 s later.
local function playCycle(now, file)
  if audio.ok then
    system.playFile(file, AUDIO_IMMEDIATE)
  else
    system.playBeep(9, 1800, 120)
    st.beepAt = now + 2500
  end
  system.vibration(false, 4)
  system.vibration(true, 4)
end

-- Stops alarm sound at once, mid-callout or mid-beep (R3).
local function stopAlarm()
  system.stopPlayback(AUDIO_IMMEDIATE)
  st.beepAt = nil
  st.tlPending = false
end

