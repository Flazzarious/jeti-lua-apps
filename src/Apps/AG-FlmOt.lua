local function init()
  loadSettings()
  recompute()
  resetSession()
  checkAudio()                -- once: five file opens (R6)

  system.registerForm(1, MENU_APPS, APP_NAME, initForm, nil, nil, closeForm)
  system.registerTelemetry(1, APP_NAME, 0, printRpm)
end

local function loop()
  local now = system.getTimeCounter()
  if now - st.lastTick < TICK_MS then
    return
  end
  st.lastTick = now

  stepTest(now)               -- before the OFF check: tests work with monitoring off (R13)
  updateLive(now)             -- settings form's Live RPM row, also while OFF

  -- Row 0: off or not fully configured (FR-012, FR-034).
  if not d.active then
    if st.state == S.FLAMEOUT then
      stopAlarm()
    end
    st.state = S.OFF
    st.rpm = nil
    updateRpmText()
    return
  end
  if st.state == S.OFF then   -- just turned on
    st.state = S.DISARMED
    st.armSince, st.lowSince, st.invalidSince, st.lost = nil, nil, nil, false
  end

  -- Always call through system: Emulator Telemetry replaces it (R9).
  local s
  if SIM and sim.idx > 1 then
    s = simRead(now)
  else
    s = system.getSensorValueByID(cfg.sId, cfg.sPar)
  end
  local valid = false
  st.sensorFound = s ~= nil
  st.rpm = nil
  if s ~= nil and s.valid then
    valid = true
    st.rpm = s.value * d.kScale
  end

  -- Row 1: Cut wins over everything (FR-016). The RPM above is still read so
  -- the window follows the spool-down.
  if switchOn(cfg.swCut) then
    onCut()
    updateRpmText()
    return
  end

  if not valid then
    onInvalid(now)            -- row 2
  else
    st.invalidSince, st.lost = nil, false
    if st.state == S.DISARMED then
      stepDisarmed(now)
    elseif st.state == S.ARMED then
      stepArmed(now)
    elseif st.state == S.FLAMEOUT then
      stepFlameout(now)
    end
  end
  -- Valid or not: the alarm keeps cycling through a telemetry loss (FR-020a).
  if st.state == S.FLAMEOUT then
    stepCycle(now)
  end
  updateRpmText()
end

local function destroy()
  if st.state == S.FLAMEOUT or st.testOn then
    stopAlarm()
  end
end

---@type JetiApp
return {
  init = init,
  loop = loop,
  destroy = destroy,
  author = "Aaron George",
  version = APP_VERSION,
  name = APP_NAME,
}
