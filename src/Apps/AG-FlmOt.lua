-- SIM (debug, R12): scripted RPM profiles in place of the sensor, chosen in
-- the form while SIM is true. Each profile is a flat list of time (ms from
-- selection), RPM pairs, linearly interpolated; RPM -1 means invalid data.
-- The last value holds after the end.
local sim = { idx = 1, t0 = 0, out = { value = 0, valid = true } }
sim.names = { "Off (real sensor)", "Normal flight", "Failed start", "Flameout", "Auto-restart", "Dropouts" }
sim.profiles = {           -- sim.names[i + 1]
  { 0, 0, 5000, 0, 25000, 20000, 28000, 45000, 36000, 35000, 60000, 35000, 65000, 120000,
    90000, 120000, 92000, 35000, 100000, 35000, 103000, 120000, 130000, 120000,
    132000, 35000, 160000, 35000 },
  { 0, 0, 5000, 0, 20000, 25000, 23000, 25000, 30000, 0 },
  { 0, 0, 3000, 0, 15000, 40000, 20000, 60000, 40000, 60000, 43000, 0 },
  { 0, 60000, 8000, 60000, 11000, 0, 16000, 0, 20000, 10000, 24000, 28000, 27000, 8000,
    30000, 8000, 34000, 20000, 38000, 45000, 46000, 35000 },
  { 0, 35000, 10000, 35000, 10001, -1, 10500, -1, 10501, 35000, 15000, 35000, 15001, -1,
    18000, -1, 18001, 35000 },
}

local function simRead(now)
  local p = sim.profiles[sim.idx - 1]
  local t = now - sim.t0
  local v = p[#p]
  for i = 1, #p - 2, 2 do
    if t < p[i + 2] then
      local a, b = p[i + 1], p[i + 3]
      if a < 0 or b < 0 then
        v = -1
      else
        v = a + (b - a) * (t - p[i]) / (p[i + 2] - p[i])
      end
      break
    end
  end
  sim.out.valid = v >= 0
  sim.out.value = v
  return sim.out
end

-- Unassigned switch = off. "On" is above half travel (R10).
local function switchOn(item)
  if item == nil then
    return false
  end
  local v = system.getInputsVal(item)
  return v ~= nil and v > 0.5
end

local function stepTest(now)            -- test alarm, rows T1-T3 (US8)
end

-- Row 1 (FR-016): Cut disarms at once and silently from any state. Arming
-- again needs the switch out of Cut and row 3 (User Story 5).
local function onCut()
  if st.state == S.FLAMEOUT then
    stopAlarm()
  end
  st.state = S.DISARMED
  st.armSince, st.lowSince, st.invalidSince = nil, nil, nil
  st.tlPending, st.lost = false, false
end

local function onInvalid(now)           -- row 2 (US6)
end

-- Row 3 (FR-014): arms once RPM has held the arming threshold for the
-- arming time. The start overshoot above idle counts like any RPM above it.
local function stepDisarmed(now)
  if st.rpm >= d.armRpm then
    st.armSince = st.armSince or now
    if now - st.armSince >= d.armMs then
      st.state = S.ARMED
      st.armSince, st.lowSince = nil, nil
      if cfg.sayArm == 1 and audio.armed then
        system.playFile(SND.armed, AUDIO_QUEUE)   -- FR-009; queued, never cuts a callout
      end
    end
  else
    st.armSince = nil
  end
end

-- Row 4 (FR-015): RPM below the flameout threshold for the detection delay.
local function stepArmed(now)
  if st.rpm < d.flRpm then
    st.lowSince = st.lowSince or now
    if now - st.lowSince >= d.detMs then
      st.state = S.FLAMEOUT
      st.lowSince, st.armSince = nil, nil
      st.cycleAt = now
      playCycle(now, SND.cycle)
    end
  else
    st.lowSince = nil
  end
end

-- Row 5 (FR-017, FR-018): the alarm clears only when RPM holds the arming
-- threshold for the arming time, usually during the relight overshoot.
-- RPM in the startup range (an auto-restart cranking) breaks the timer and
-- starts nothing new; the same alarm continues.
local function stepFlameout(now)
  if st.rpm >= d.armRpm then
    st.armSince = st.armSince or now
    if now - st.armSince >= d.armMs then
      stopAlarm()
      st.state = S.ARMED
      st.armSince, st.lowSince = nil, nil
      if cfg.sayRel == 1 and audio.relit then
        system.playFile(SND.relit, AUDIO_QUEUE)
      end
    end
  else
    st.armSince = nil
  end
end

-- Row 6 (SC-012): a new cycle every 5 s, plus the second fallback beep burst.
local function stepCycle(now)
  if st.beepAt and now >= st.beepAt then
    system.playBeep(9, 1800, 120)
    st.beepAt = nil
  end
  if now - st.cycleAt >= CYCLE_MS then
    st.cycleAt = st.cycleAt + CYCLE_MS
    if now - st.cycleAt >= CYCLE_MS then
      st.cycleAt = now          -- fell more than a cycle behind: restart the rhythm
    end
    playCycle(now, SND.cycle)
  end
end

-- Whole RPM with a thousands separator: 112400 -> "112,400".
local function fmtRpm(r)
  if r >= 1000 then
    return string.format("%d,%03d", r // 1000, r % 1000)
  end
  return tostring(r)
end

-- "112,400" for the window, rebuilt only when RPM / 100 changes.
local function updateRpmText()
  local h = -1
  if st.rpm ~= nil then
    h = math.floor(st.rpm / 100 + 0.5)
  end
  if h == st.rpmHundreds then
    return
  end
  st.rpmHundreds = h
  if h < 0 then
    st.rpmText = TXT.noData
  else
    st.rpmText = fmtRpm(h * 100)
  end
end

