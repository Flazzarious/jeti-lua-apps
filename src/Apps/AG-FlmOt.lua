-- Window display state (data-model.md).
local function stateText()
  if st.testOn then
    return TXT.test
  elseif st.state == S.OFF then
    return TXT.off
  elseif not st.sensorFound then
    return TXT.noSensor
  elseif st.state == S.FLAMEOUT then
    return TXT.flameout
  elseif st.lost then
    return TXT.noTel
  elseif st.state == S.ARMED then
    return TXT.armed
  end
  return TXT.disarmed
end

-- Text layout: any window size, theme colors.
local function drawText(w)
  local r, g, b = lcd.getFgColor()
  lcd.setColor(r, g, b)
  if st.state == S.FLAMEOUT then
    lcd.drawText(4, 2, TXT.flameout, FONT_BIG)   -- dominant (FR-031)
    lcd.drawText(w - 4 - lcd.getTextWidth(FONT_MINI, st.rpmText), 24, st.rpmText, FONT_MINI)
    return
  end
  lcd.drawText(4, 2, stateText(), FONT_MINI)
  lcd.drawText(w - 4 - lcd.getTextWidth(FONT_NORMAL, st.rpmText), 2, st.rpmText, FONT_NORMAL)
end

local function printRpm(w, h)
  drawText(w)
end

