local KEYS = {
  "en", "sId", "sPar", "sLbl", "scl", "swCut", "idle", "maxR", "armP", "flP",
  "armT", "detT", "lossT", "sayArm", "sayRel", "swTest", "cfgV",
}  -- 17 keys (limit 30)
local DEFAULTS = {
  en = 0, sId = 0, sPar = 0, sLbl = "", scl = 1, idle = 0, maxR = 0, armP = 90,
  flP = 70, armT = 30, detT = 10, lossT = 20, sayArm = 0, sayRel = 0, cfgV = 1,
}  -- swCut and swTest default to nil
local RANGES = {
  en = { 0, 1 }, scl = { 1, 4 }, idle = { 0, 1500 }, maxR = { 0, 3000 },
  armP = { 50, 98 }, flP = { 20, 95 }, armT = { 10, 100 }, detT = { 3, 50 },
  lossT = { 5, 100 }, sayArm = { 0, 1 }, sayRel = { 0, 1 },
}
local SCALES = { 1, 10, 100, 1000 }   -- sensor scale x1 .. x1000 (FR-006a)

local cfg = {}

local function save(key, value)
  cfg[key] = value
  system.pSave(key, value)
end

local function clamp(v, lo, hi)
  if v < lo then
    return lo
  elseif v > hi then
    return hi
  end
  return v
end

local function loadSettings()
  for _, key in ipairs(KEYS) do
    cfg[key] = system.pLoad(key, DEFAULTS[key])
  end
  for key, r in pairs(RANGES) do
    local v = clamp(cfg[key], r[1], r[2])
    if v ~= cfg[key] then
      save(key, v)
    end
  end
  -- Combinations the form never allows (data-model.md "Validation").
  if cfg.flP >= cfg.armP then
    save("armP", DEFAULTS.armP)
    save("flP", DEFAULTS.flP)
  end
  if cfg.maxR ~= 0 and cfg.maxR <= cfg.idle then
    save("maxR", 0)
  end
  if cfg.en == 1 and (cfg.sId == 0 or cfg.swCut == nil or cfg.idle == 0) then
    save("en", 0)
  end
end

------------------------------------------------------------------------------
-- Derived values: recomputed only when a setting changes, never per tick.
------------------------------------------------------------------------------

local d = {
  active = false,           -- monitoring on and fully configured (FR-003, FR-012)
  kScale = 1,               -- sensor value -> RPM
  idleRpm = 0, armRpm = 0, flRpm = 0, fullRpm = 1,
  armMs = 3000, detMs = 1000, lossMs = 2000,
}

local function recompute()
  d.active = cfg.en == 1 and cfg.sId ~= 0 and cfg.swCut ~= nil and cfg.idle > 0
  d.kScale = SCALES[cfg.scl]
  d.idleRpm = cfg.idle * 100
  d.armRpm = d.idleRpm * cfg.armP // 100
  d.flRpm = d.idleRpm * cfg.flP // 100
  if cfg.maxR ~= 0 then
    d.fullRpm = cfg.maxR * 100
  else
    d.fullRpm = math.max(1, 4 * d.idleRpm)
  end
  d.armMs = cfg.armT * 100
  d.detMs = cfg.detT * 100
  d.lossMs = cfg.lossT * 100
end

------------------------------------------------------------------------------
-- Session state (not persisted; reset by init on every model load).
------------------------------------------------------------------------------

local st = {}

local function resetSession()
  st.state = d.active and S.DISARMED or S.OFF
  st.rpm = nil              -- last valid RPM; nil while invalid
  st.sensorFound = true     -- false: the sensor isn't in the model's list (FR-022)
  st.invalidSince = nil
  st.lost = false           -- invalid for at least lossMs (NO TELEMETRY)
  st.armSince = nil         -- RPM >= armRpm since (DISARMED, FLAMEOUT)
  st.lowSince = nil         -- RPM < flRpm since (ARMED)
  st.cycleAt = 0            -- start of the current alarm cycle
  st.beepAt = nil           -- second fallback beep burst due (R6)
  st.tlPending = false      -- play cycletl.wav at the next cycle (R4)
  st.testOn = false         -- a test alarm is playing (R13)
  st.testPrev = true        -- a test switch already on at load needs a toggle
  st.rpmText = TXT.noData
  st.rpmHundreds = -1
  st.lastTick = system.getTimeCounter()
  st.liveAt = 0             -- last Live RPM row update (form open only)
end

