local function recomputeDensity()
  local imperial = UNITS_IMPERIAL[cfg.units]
  densActive = cfg.densOn == 1 and cfg.sType == 1
  local elevM = imperial and dens.ftToM(cfg.elev) or cfg.elev
  local tempC = nil         -- nil = standard temperature for the elevation
  if cfg.tSrc == 2 then
    tempC = imperial and dens.fToC(cfg.temp) or cfg.temp
  elseif cfg.tSrc == 3 and ts.stat == 2 then
    tempC = ts.useC
  end
  if densActive then
    kDens = dens.factor(elevM, tempC)
  else
    kDens = 1
  end
  -- Temperature in use, for the full-screen row and the settings status.
  local t = tempC or dens.stdTempC(elevM)
  if imperial then
    t = dens.cToF(t)
  end
  tempText = tostring(math.floor(t + 0.5))
  tempUnitText = imperial and "°F" or "°C"
  local inUse = "Temp: " .. tempText .. " " .. tempUnitText
  if cfg.tSrc == 1 then
    tempLabel, tStatText = TXT_TEMP.std, inUse .. " standard"
  elseif cfg.tSrc == 2 then
    tempLabel, tStatText = TXT_TEMP.man, inUse .. " manual"
  elseif ts.stat == 2 then
    tempLabel, tStatText = TXT_TEMP.sens, inUse .. " from " .. cfg.tLbl
  else
    tempLabel, tStatText = TXT_TEMP.out, "Sensor not available - using standard"
  end
  local pct = math.floor((kDens - 1) * 100 + 0.5)
  densPctText = (pct >= 0 and "+" or "") .. pct .. "%"
  if cfg.sType == 2 then
    densRowText = TXT_GPS
  elseif densActive then
    densRowText = densPctText
  else
    densRowText = TXT_OFF
  end
  elevText = tostring(cfg.elev)
  elevUnitText = imperial and "ft" or "m"
end

local function recomputeScale()
  local fs = cfg.fScale
  if fs == 0 then
    fs = math.ceil(cfg.vOver * 1.15 / 10) * 10
  end
  fs = math.max(fs, 10)
  fullScale = fs
  fStall = clamp(cfg.vStall * kDens / fs, 0, 1)
  fLand = clamp(cfg.vLand * kDens / fs, 0, 1)
  fOver = clamp(cfg.vOver / fs, 0, 1)
  scaleStep = gauge.scaleStep(fs)
  local labels = {}
  for i = 0, fs // scaleStep do
    labels[i + 1] = tostring(math.floor(i * scaleStep))
  end
  scaleLabels = labels
  stallText = tostring(cfg.vStall)
  overText = tostring(cfg.vOver)
  scaleVer = scaleVer + 1
end

local function recomputeUnitText()
  unitText = UNITS_TEXT[cfg.units]
  unitSpoken = UNITS_SPOKEN[cfg.units]
end

