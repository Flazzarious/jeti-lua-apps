  drawDial(L, w, h)
  local x = L.colX
  setColor(C_TEXT)
  lcd.drawText(x, 0, curText, L.numFont)
  setColor(C_SCALE)
  lcd.drawText(x, L.hNum, unitText, FONT_MINI)
  drawMax(x, L.maxLabelY, L.maxValY, FONT_NORMAL)
end

-- One full-screen panel row: small label left, value right-aligned with its
-- unit, both bottom-aligned.
local function drawPanelRow(L, i, label, value, unit, labelColor)
  local y = L.rowY + i * L.rowH
  local x = L.panelR
  if unit then
    x = x - lcd.getTextWidth(FONT_MINI, unit)
    setColor(C_MINOR)
    lcd.drawText(x, y + L.hNorm - L.hMini, unit, FONT_MINI)
    x = x - 3
  end
  x = x - lcd.getTextWidth(FONT_NORMAL, value)
  setColor(C_TEXT)
  lcd.drawText(x, y, value, FONT_NORMAL)
  setColor(labelColor or C_MINOR)
  lcd.drawText(L.panelX, y + L.hNorm - L.hMini, label, FONT_MINI)
end

local function drawFull(w, h)
  local L = layoutFor(layFull, w, h, buildFull)
  drawDial(L, w, h)
  setColor(C_TEXT)
  local tw = lcd.getTextWidth(L.numFont, curText)
  lcd.drawText(L.cx - tw // 2, L.cy - L.hNum // 2 - 2, curText, L.numFont)
  setColor(C_SCALE)
  tw = lcd.getTextWidth(L.unitFont, unitText)
  lcd.drawText(L.cx - tw // 2, L.cy + L.hNum // 2, unitText, L.unitFont)
  -- MAX in the open bottom of the dial, centered under the speed.
  local lw = lcd.getTextWidth(FONT_MINI, TXT_MAX)
  local vw = lcd.getTextWidth(FONT_BIG, maxText)
  setColor(C_MINOR)
  lcd.drawText(L.cx - lw // 2, L.maxLabelY, TXT_MAX, FONT_MINI)
  setColor(COLORS[cfg.colMax])
  lcd.drawText(L.cx - vw // 2, L.maxValY, maxText, FONT_BIG)
  -- Side panel (spec US3 #2a). DENSITY is always shown; ELEV, TEMP (FR-044)
  -- and the uncorrected RAW speed only while correction is active. A rejected
  -- sensor shows "SENSOR OUT" in the overspeed color, with the standard
  -- temperature in use as its value.
  drawPanelRow(L, 0, TXT_STALL, stallText, unitText)
  drawPanelRow(L, 1, TXT_OVERSPEED, overText, unitText)
  drawPanelRow(L, 2, TXT_DENSITY, densRowText, nil)
  if densActive then
    drawPanelRow(L, 3, TXT_ELEVATION, elevText, elevUnitText)
    drawPanelRow(L, 4, tempLabel, tempText, tempUnitText,
      tempLabel == TXT_TEMP.out and C_ZONE or nil)
    drawPanelRow(L, 5, TXT_SENSOR, sensText, unitText)
  end
  if DEBUG_CPU then
    -- This call's CPU share at its end, and the worst seen (top-left corner).
    local c = system.getCPU()
    if c > cpuPeak then
      cpuPeak = c
    end
    setColor(C_ZONE)
    lcd.drawNumber(2, 0, c, FONT_MINI)
    lcd.drawNumber(26, 0, cpuPeak, FONT_MINI)
  end
end

local function drawStrip(w, h)
  local L = layoutFor(layStrip, w, h, buildStrip)
  setColor(C_FACE)
  lcd.drawFilledRectangle(0, 0, w, h)
  -- Current speed and unit on the left, MAX and its value on the right.
  setColor(C_TEXT)
  lcd.drawText(L.barX, L.numY, curText, L.numFont)
  setColor(C_SCALE)
  lcd.drawText(L.barX + lcd.getTextWidth(L.numFont, curText) + 3, L.miniY, unitText, FONT_MINI)
  local vx = w - 2 - lcd.getTextWidth(FONT_MINI, maxText)
  setColor(COLORS[cfg.colMax])
  lcd.drawText(vx, L.miniY, maxText, FONT_MINI)
  setColor(C_MINOR)
  lcd.drawText(vx - 3 - lcd.getTextWidth(FONT_MINI, TXT_MAX), L.miniY, TXT_MAX, FONT_MINI)
  -- Bar: track, overspeed zone, value (overspeed color past the mark), max tick.
  local x0, y, bw, bh = L.barX, L.barY, L.barW, L.barH
  local xo = x0 + round(bw * fOver)
  setColor(C_TRACK)
  lcd.drawFilledRectangle(x0, y + 1, bw, bh - 2)
  setColor(C_ZONE)
  lcd.drawFilledRectangle(xo, y + 1, x0 + bw - xo, bh - 2)
  if shownSpd ~= nil then
    local xv = x0 + round(bw * math.min(shownSpd / fullScale, 1))
    setColor(COLORS[cfg.colCur])
    lcd.drawFilledRectangle(x0, y, math.min(xv, xo) - x0, bh)
    if xv > xo then
      setColor(C_ZONE)
      lcd.drawFilledRectangle(xo, y, xv - xo, bh)
    end
  end
  if maxSpd > 0 then
    setColor(COLORS[cfg.colMax])
    local xm = x0 + round(bw * math.min(maxSpd / fullScale, 1))
    lcd.drawFilledRectangle(xm - 1, y - 2, 2, bh + 3)
  end
end

local function printGauge(w, h)
  if not gaugeOk then
    -- FR-013a: not a DS-24 II. Callouts and warnings still run in loop().
    local r, g, b = lcd.getFgColor()
    lcd.setColor(r, g, b)
    local tw = lcd.getTextWidth(FONT_MINI, TXT_NOTICE)
    lcd.drawText((w - tw) // 2, (h - lcd.getTextHeight(FONT_MINI)) // 2, TXT_NOTICE, FONT_MINI)
    return
  end
  if not rend then
    rend = lcd.renderer()
  end
  -- Only the emulator hides a title bar inside the window (see TITLE_H).
  liveLines = w == 157 or w == 320
  if liveLines then
    h = h - TITLE_H
  end
  if h < 45 then
    drawStrip(w, h)
  elseif w < 250 then
    drawRound(w, h)
  else
    drawFull(w, h)
  end
end

