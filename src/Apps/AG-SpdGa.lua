-- App-voice number file for n, or nil to fall back to the transmitter voice
-- for this phrase (over 500, or the file is missing: FR-033). Builds a path
-- and opens a file, so call it only when something is about to be spoken.
local function numFile(n)
  if not useAppVoice or n < 0 or n > VOICE.maxNum then
    return nil
  end
  local path = VOICE.dir .. n .. ".wav"
  if fileExists(path) then
    return path
  end
  return nil
end

