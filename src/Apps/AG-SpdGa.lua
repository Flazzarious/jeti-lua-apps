-- A temperature value reports "°C" or "°F": 3 bytes in UTF-8, 2 in Latin-1
-- (the transmitter's encoding is unverified, R15).
local function isTempUnit(unit)
  local last = string.sub(unit, -1)
  return (#unit == 2 or #unit == 3) and (last == "C" or last == "F")
end

-- Adds the "<label> (not found)" entry for a saved sensor that isn't present
-- (R4). Returns its index.
local function addNotFound(labels, ids, pars, label, id, par)
  local n = #labels + 1
  labels[n], ids[n], pars[n] = label .. " (not found)", id, par
  return n
end

-- Rebuilds the speed and temperature sensor lists in one pass (late sensors
-- appear, R4, R15). Returns both selections.
local function buildSensorList()
  sensorLabels, sensorIds, sensorPars = { "(none)" }, { 0 }, { 0 }
  tempLabels, tempIds, tempPars = { "(none)" }, { 0 }, { 0 }
  notFoundIdx, tempNotFoundIdx = 0, 0
  local selected, tSelected = 1, 1
  local parent = ""
  for _, s in ipairs(system.getSensors()) do
    if s.param == 0 then
      parent = s.label
    elseif s.type ~= 5 and s.type ~= 9 then
      local text = (parent ~= "") and (parent .. " / " .. s.label) or s.label
      local n = #sensorLabels + 1
      sensorLabels[n], sensorIds[n], sensorPars[n] = text, s.id, s.param
      if s.id == cfg.sId and s.param == cfg.sPar then
        selected = n
      end
      if isTempUnit(s.unit or "") then
        n = #tempLabels + 1
        tempLabels[n], tempIds[n], tempPars[n] = text, s.id, s.param
        if s.id == cfg.tId and s.param == cfg.tPar then
          tSelected = n
        end
      end
    end
  end
  if cfg.sId ~= 0 and selected == 1 then
    notFoundIdx = addNotFound(sensorLabels, sensorIds, sensorPars, cfg.sLbl, cfg.sId, cfg.sPar)
    selected = notFoundIdx
  end
  if cfg.tId ~= 0 and tSelected == 1 then
    tempNotFoundIdx = addNotFound(tempLabels, tempIds, tempPars, cfg.tLbl, cfg.tId, cfg.tPar)
    tSelected = tempNotFoundIdx
  end
  return selected, tSelected
end

