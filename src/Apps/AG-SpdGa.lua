-- Largest of the given fonts where sample text fits in maxW x maxH.
local function fitFont(fonts, sample, maxW, maxH)
  for i = 1, #fonts do
    local f = fonts[i]
    if lcd.getTextWidth(f, sample) <= maxW and lcd.getTextHeight(f) <= maxH then
      return f
    end
  end
  return fonts[#fonts]
end

local NUM_FONTS = { FONT_MAXI, FONT_BIG, FONT_NORMAL, FONT_MINI }

-- Tick end points and label positions for a dial layout.
local function buildScale(L, dial, minorPer, withLabels)
  local mx1, my1, mx2, my2 = {}, {}, {}, {}
  local nx1, ny1, nx2, ny2 = {}, {}, {}, {}
  local lx, ly = {}, {}
  local font = L.labelFont
  local hLabel = lcd.getTextHeight(font)
  local rOut, rMaj, rMin = L.tickOut, L.tickOut - L.majorLen, L.tickOut - L.minorLen
  for i = 1, #scaleLabels do
    local v = (i - 1) * scaleStep
    local c, s = gauge.point(dial, v / fullScale)
    mx1[i], my1[i] = round(L.cx + c * rOut), round(L.cy + s * rOut)
    mx2[i], my2[i] = round(L.cx + c * rMaj), round(L.cy + s * rMaj)
    if withLabels then
      local tw = lcd.getTextWidth(font, scaleLabels[i])
      lx[i] = round(L.cx + c * L.labelR - tw / 2)
      ly[i] = round(L.cy + s * L.labelR - hLabel / 2)
    end
    for m = 1, minorPer do
      local f = (v + scaleStep * m / (minorPer + 1)) / fullScale
      if f < 1 then
        c, s = gauge.point(dial, f)
        local k = #nx1 + 1
        nx1[k], ny1[k] = round(L.cx + c * rOut), round(L.cy + s * rOut)
        nx2[k], ny2[k] = round(L.cx + c * rMin), round(L.cy + s * rMin)
      end
    end
  end
  L.mx1, L.my1, L.mx2, L.my2 = mx1, my1, mx2, my2
  L.nx1, L.ny1, L.nx2, L.ny2 = nx1, ny1, nx2, ny2
  L.lx, L.ly = lx, ly
  L.labels = withLabels
end

-- Glow bands for a layout: n bands step px apart, alpha falling
-- geometrically from GLOW[1] to GLOW[2] so neighbors differ only slightly.
-- The bands are nested filled ring segments, all starting at the arc:
-- layer k reaches k * step inward, so the glow builds up toward the arc
-- and neighbors share no seams. Each layer's alpha is solved so the total
-- in band k is the target A_k: (1 - A_k) = (1 - a_k)(1 - A_k+1).
local function buildGlow(L, step, n)
  L.glowStep, L.glowN = step, n
  local A, a = {}, {}
  local k = (GLOW[2] / GLOW[1]) ^ (1 / (n - 1))
  for i = 1, n do
    A[i] = GLOW[1] * k ^ (i - 1)
  end
  a[n] = A[n]
  for i = n - 1, 1, -1 do
    a[i] = 1 - (1 - A[i]) / (1 - A[i + 1])
  end
  L.glowA, L.glowT = a, A
end

-- Double window (transmitter 150 x 68): a small 270-degree dial on the left
-- without scale numbers (too small to read), current speed and MAX on the
-- right. Stall and overspeed stay as rim marks only (FR-016 "SHOULD").
local function buildRound(L, w, h)
  local R = math.floor(math.min((h - 4) / 1.707, w * 0.55 / 2))
  L.R, L.cx = R, 2 + R
  L.cy = math.floor((h - R * 1.707) / 2 + R)
  L.arcR, L.arcW, L.markW = R - 3, 4, 3
  buildGlow(L, 2, 6)
  L.tickOut, L.majorLen, L.minorLen = R - 7, 4, 2
  L.labelFont = FONT_MINI
  L.dial, L.face, L.showMarks = roundDial, true, true
  buildScale(L, roundDial, 0, false)
  L.hMini = lcd.getTextHeight(FONT_MINI)
  L.colX = 2 * R + 8
  local colW = w - L.colX - 2
  L.numFont = fitFont(NUM_FONTS, "888", colW, h - 2 * L.hMini - lcd.getTextHeight(FONT_NORMAL))
  L.hNum = lcd.getTextHeight(L.numFont)
  L.maxValY = h - lcd.getTextHeight(FONT_NORMAL)
  L.maxLabelY = L.maxValY - L.hMini
end

-- Full screen (transmitter 316 x 159): dial about 180 px across on the
-- left, MAX in its open bottom; one-line panel rows on the right.
local function buildFull(L, w, h)
  local R = math.floor(math.min((h - 4) / 1.707, (w - 130) / 2 - 2))
  local big = R >= 110        -- emulator-sized dial: larger scale text
  L.R, L.cx = R, 2 + R
  L.cy = math.floor((h - R * 1.707) / 2 + R)
  L.arcR, L.arcW, L.markW = R - 5, 7, 5
  buildGlow(L, 3, 9)
  L.tickOut, L.majorLen, L.minorLen = R - 11, 9, 5
  L.labelFont = big and FONT_NORMAL or FONT_MINI
  L.unitFont = L.labelFont
  L.labelR = R - (big and 36 or 28)
  L.dial, L.face, L.showMarks = roundDial, true, true
  buildScale(L, roundDial, big and 4 or 1, true)
  L.numFont = fitFont(NUM_FONTS, "888", R, R // 2)
  L.hNum, L.hMini = lcd.getTextHeight(L.numFont), lcd.getTextHeight(FONT_MINI)
  L.hBig, L.hNorm = lcd.getTextHeight(FONT_BIG), lcd.getTextHeight(FONT_NORMAL)
  L.maxValY = h - L.hBig - 1
  L.maxLabelY = L.maxValY - L.hMini
  -- Panel: up to six one-line rows, label left and value right-aligned.
  L.panelX, L.panelR = 2 * R + 10, w - 2
  L.rowH = math.min(h // 6, L.hNorm + 12)
  L.rowY = (h - 6 * L.rowH) // 2
end

-- Single window (transmitter 150 x 23): no room for an arc. Current speed
-- and MAX on one line over a thin horizontal bar: value in the current-speed
