-- Temperature sensor, every ts.periodMs (R15, data-model.md). A bad read falls
-- back to standard at once; after a rejection, two good reads in a row are
-- needed to resume. The first read after (re)start needs only one. Changes
-- only the density factor, never callout state (FR-041, FR-043).
local function readTemp(now)
  if ts.stat == 0 or now - ts.nextRead < 0 then
    return
  end
  ts.nextRead = now + ts.periodMs
  local e = nil
  if cfg.tId ~= 0 then
    e = system.getSensorByID(cfg.tId, cfg.tPar)   -- through system (R3); unit needed
  end
  local rc = nil            -- good reading, deg C
  if e ~= nil and e.valid then
    local isF = string.sub(e.unit or "", -1) == "F"
    -- Limits in the system the user sees (FR-023).
    local v = e.value
    if UNITS_IMPERIAL[cfg.units] then
      v = isF and v or dens.cToF(v)
      if v >= LIM.tempF[1] and v <= LIM.tempF[2] then
        rc = dens.fToC(v)
      end
    else
      v = isF and dens.fToC(v) or v
      if v >= LIM.tempC[1] and v <= LIM.tempC[2] then
        rc = v
      end
    end
  end
  local oldStat, oldUse = ts.stat, ts.useC
  if ts.stat == 1 then
    if rc == nil then
      ts.good, ts.ever = 0, true
    elseif not ts.ever then
      ts.stat, ts.useC, ts.ever = 2, rc, true
    else
      ts.good = ts.good + 1
      if ts.good >= 2 then
        ts.stat, ts.useC = 2, rc
      end
    end
  elseif rc == nil then
    ts.stat, ts.good, ts.useC, ts.ever = 1, 0, nil, true
  elseif math.abs(rc - ts.useC) >= 1 then
    ts.useC = rc              -- 1 deg C hysteresis (FR-041)
  end
  if ts.stat ~= oldStat or ts.useC ~= oldUse then
    recomputeDensity()
    recomputeScale()
    if formOpen then
      updateDensityRows()
    end
  end
end

local function init()
  loadSettings()
  voiceOk = checkVoiceFiles()   -- once: 13 file opens (R14)
  recomputeAll()
  resetSession()

  -- 3-degree steps for visible edges: 5-degree steps looked choppy on the
  -- transmitter, which enlarges Lua drawing about 1.45x (2026-10-03).
  -- 10-degree steps for the translucent glow bands, where they don't show
  -- and save renderer calls every frame.
  roundDial = gauge.newDial(90, 225, 270)
  faceCircle = gauge.newCircle(90)
  glowDial = gauge.newDial(54, 225, 270)   -- 5-degree steps (10 looked polygonal)
  gaugeOk = string.find(system.getDeviceType() or "", "24 II", 1, true) ~= nil

  system.registerForm(1, MENU_APPS, APP_NAME, initForm, keyForm, nil, closeForm)
  system.registerTelemetry(1, APP_NAME, 0, printGauge)
  -- Size 4 (no status bar), as DFM-InsP uses: size 3 is covered by the desktop's
  -- model tile on the DS-24 II (emulator, 2026-09-27).
  -- Distinct name so the pilot can tell the two apart in Displayed telemetry
  -- (transmitter test, 2026-10-03). Size 4 has no title bar, so it shows
  -- only in that list.
  system.registerTelemetry(2, APP_NAME .. " (full screen)", 4, printGauge)

  -- FR-028: tell the pilot the app is running and configured.
  -- Each announcement is wholly in the app voice or wholly in the fallback.
  if cfg.startAnn == 1 then
    if cfg.cal ~= 100 then
      local nf = numFile(cfg.cal)
      if nf then
        system.playFile(VOICE.cal, AUDIO_QUEUE)
        system.playFile(nf, AUDIO_QUEUE)
        system.playFile(VOICE.pct, AUDIO_QUEUE)
      else
        system.playFile(SND_CAL, AUDIO_QUEUE)
        system.playNumber(cfg.cal, 0, "%")
      end
    end
    local nf = numFile(cfg.vStall)
    if nf then
      system.playFile(VOICE.stallAt, AUDIO_QUEUE)
      system.playFile(nf, AUDIO_QUEUE)
      system.playFile(snd.unit, AUDIO_QUEUE)
    else
      system.playFile(SND_STALL_AT, AUDIO_QUEUE)
      system.playNumber(cfg.vStall, 0, unitSpoken)
    end
  end
end

local function loop()
  local now = system.getTimeCounter()
  if now - lastTick < TICK_MS then
    return
  end
  lastTick = now
  readTemp(now)             -- before the early return: tracked even with no speed

  -- Always call through system: Emulator Telemetry replaces it (R3).
  local s = nil
  if cfg.sId ~= 0 then
    s = system.getSensorValueByID(cfg.sId, cfg.sPar)
  end
  if s == nil or not s.valid then
    if sensorSpd ~= nil then
      sensorSpd, shownSpd = nil, nil
      curRounded, curText = nil, TXT_NO_DATA
      sensRounded, sensText = nil, TXT_NO_DATA
    end
    return                  -- no data: no flags, max, warnings or callouts
  end

  sensorSpd = s.value * kSensor
  shownSpd = sensorSpd * kDens

  -- Flight flags use sensor speed (FR-011).
  if sensorSpd > cfg.vLand / 2 then
    everAboveHalf = true
  end
  if sensorSpd > cfg.vLand then
    everAboveLanding = true
    belowLanding = false
  elseif everAboveLanding then
    belowLanding = true
  end

  local onSw, contSw = switchOn(cfg.swOn), switchOn(cfg.swCont)
  updateMax(now)
  checkWarnings(onSw or contSw)
  checkCallout(now, onSw, contSw)
end

