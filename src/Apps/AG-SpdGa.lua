local function save(key, value)
  cfg[key] = value
  system.pSave(key, value)
end

local function clamp(v, lo, hi)
  if v < lo then
    return lo
  elseif v > hi then
    return hi
  end
  return v
end

local function clampKey(key, lo, hi)
  local v = clamp(cfg[key], lo, hi)
  if v ~= cfg[key] then
    save(key, v)
  end
end

local function loadSettings()
  for _, key in ipairs(KEYS) do
    cfg[key] = system.pLoad(key, DEFAULTS[key])
  end
  if cfg.temp == nil then
    cfg.temp = UNITS_IMPERIAL[cfg.units] and 59 or 15
  end
  -- cfgV 1 -> 2 (0.1.0 had a "Use standard temperature" checkbox, R16). A
  -- fresh install runs this too and ends with the default, Standard.
  if system.pLoad("cfgV", 1) < 2 then
    save("tSrc", system.pLoad("tStd", 1) == 1 and 1 or 2)
    system.pSave("tStd", nil)
    save("cfgV", 2)
  end
  -- Values saved by an older version may be outside today's limits (Edge Cases).
  for key, r in pairs(RANGES) do
    clampKey(key, r[1], r[2])
  end
  if cfg.fScale ~= 0 and cfg.fScale < 10 then
    save("fScale", 10)
  end
  if UNITS_IMPERIAL[cfg.units] then
    clampKey("elev", LIM.elevFt[1], LIM.elevFt[2])
    clampKey("temp", LIM.tempF[1], LIM.tempF[2])
  else
    clampKey("elev", LIM.elevM[1], LIM.elevM[2])
    clampKey("temp", LIM.tempC[1], LIM.tempC[2])
  end
end

